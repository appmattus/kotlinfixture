package com.appmattus.kotlinfixture.resolver

import android.annotation.SuppressLint
import com.appmattus.kotlinfixture.Context
import com.appmattus.kotlinfixture.Unresolved
import com.appmattus.kotlinfixture.typeOf
import kotlinx.datetime.DatePeriod
import kotlinx.datetime.DateTimePeriod
import kotlinx.datetime.FixedOffsetTimeZone
import kotlinx.datetime.LocalDate
import kotlinx.datetime.LocalDateTime
import kotlinx.datetime.LocalTime
import kotlinx.datetime.TimeZone
import kotlinx.datetime.UtcOffset
import kotlinx.datetime.YearMonth
import kotlinx.datetime.toKotlinDatePeriod
import kotlinx.datetime.toKotlinFixedOffsetTimeZone
import kotlinx.datetime.toKotlinLocalDate
import kotlinx.datetime.toKotlinLocalDateTime
import kotlinx.datetime.toKotlinLocalTime
import kotlinx.datetime.toKotlinTimeZone
import kotlinx.datetime.toKotlinUtcOffset
import java.time.Duration
import java.time.Period
import java.time.ZoneId
import java.time.ZoneOffset

/**
 * Generates kotlinx-datetime types when kotlinx-datetime is on the classpath. Values are converted from the
 * equivalent `java.time` values generated by [TimeResolver], so they follow the same configuration and ranges.
 * `kotlin.time.Instant`, which kotlinx-datetime uses for instants, is generated by [TimeResolver].
 */
@SuppressLint("NewApi")
internal class KotlinxDateTimeResolver : Resolver {

    @Suppress("ComplexMethod")
    override fun resolve(context: Context, obj: Any): Any? {
        return if (KotlinxDateTimeConverter.isAvailable) {
            when (obj) {
                LocalDate::class -> context.generateLocalDate()
                LocalDateTime::class -> context.resolveJava<java.time.LocalDateTime>().toKotlinLocalDateTime()
                LocalTime::class -> context.resolveJava<java.time.LocalTime>().toKotlinLocalTime()
                YearMonth::class -> context.generateLocalDate().let { YearMonth(it.year, it.month) }
                TimeZone::class -> context.resolveJava<ZoneId>().toKotlinTimeZone()
                FixedOffsetTimeZone::class -> context.resolveJava<ZoneOffset>().toKotlinFixedOffsetTimeZone()
                UtcOffset::class -> context.resolveJava<ZoneOffset>().toKotlinUtcOffset()
                DatePeriod::class -> context.resolveJava<Period>().toKotlinDatePeriod()
                DateTimePeriod::class -> context.generateDateTimePeriod()
                else -> Unresolved.Unhandled
            }
        } else {
            Unresolved.Unhandled
        }
    }

    private inline fun <reified T> Context.resolveJava(): T = resolve(typeOf<T>()) as T

    private fun Context.generateLocalDate(): LocalDate = resolveJava<java.time.LocalDate>().toKotlinLocalDate()

    private fun Context.generateDateTimePeriod(): DateTimePeriod {
        val period = resolveJava<Period>()
        val duration = resolveJava<Duration>()

        return DateTimePeriod(
            years = period.years,
            months = period.months,
            days = period.days,
            nanoseconds = duration.toNanos()
        )
    }
}
